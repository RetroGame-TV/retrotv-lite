// No Nintendo code, graphics, sound, BIOS or ROM assets are used.
import fs from 'node:fs';
import path from 'node:path';
const code=[], labels=new Map(), fixups=[];
const emit=(...b)=>code.push(...b);
const label=n=>labels.set(n,0x8000+code.length);
const branch=(op,n)=>{emit(op,0);fixups.push([code.length-1,n,true]);};
const jump=n=>{emit(0x4c,0,0);fixups.push([code.length-2,n,false]);};
const address=(op,n)=>{emit(op,0,0);fixups.push([code.length-2,n,false]);};
label('reset'); emit(0x78,0xd8,0xa2,0xff,0x9a,0xe8,0x8e,0x00,0x20,0x8e,0x01,0x20,0x8e,0x10,0x40);
label('wait1');emit(0x2c,0x02,0x20);branch(0x10,'wait1');
label('wait2');emit(0x2c,0x02,0x20);branch(0x10,'wait2');
// Battery-backed PRG RAM starts with a recognizable value and survives reboot.
emit(0xad,0x00,0x60);branch(0xd0,'ramReady');emit(0xa9,0x52,0x8d,0x00,0x60);label('ramReady');
emit(0xa9,0x3f,0x8d,0x06,0x20,0xa9,0,0x8d,0x06,0x20,0xa2,0);
label('paletteLoop');address(0xbd,'palette');emit(0x8d,0x07,0x20,0xe8,0xe0,32);branch(0xd0,'paletteLoop');
emit(0xa2,0,0xa9,0xff);label('clearSprites');emit(0x9d,0x00,0x02,0xe8);branch(0xd0,'clearSprites');
emit(0xa9,100,0x8d,0x00,0x02,0x8d,0x03,0x02,0xa9,1,0x8d,0x01,0x02,0xa9,0,0x8d,0x02,0x02);
// Tone from pulse channel, to exercise the real audio path (low volume).
emit(0xa9,1,0x8d,0x15,0x40,0xa9,0x34,0x8d,0x00,0x40,0xa9,0xfd,0x8d,0x02,0x40,0xa9,0x08,0x8d,0x03,0x40);
emit(0xa9,0x10,0x8d,0x01,0x20);
label('frame');emit(0x2c,0x02,0x20);branch(0x10,'frame');
emit(0xa9,0,0x8d,0x03,0x20,0xa9,2,0x8d,0x14,0x40,0xa9,1,0x8d,0x16,0x40,0xa9,0,0x8d,0x16,0x40,0x85,0,0xa2,8);
label('pad');emit(0xad,0x16,0x40,0x4a,0x26,0,0xca);branch(0xd0,'pad');
for(const [mask,opcode,offset,next] of [[1,0xee,3,'left'],[2,0xce,3,'down'],[4,0xee,0,'up'],[8,0xce,0,'scroll']]){
  emit(0xa5,0,0x29,mask);branch(0xf0,next);emit(opcode,offset,2);label(next);
}
emit(0xa9,0,0x8d,0x05,0x20,0x8d,0x05,0x20);jump('frame');
label('nmi');emit(0x40);label('palette');emit(...[0x0f,0x19,0x29,0x39,0x0f,0x11,0x21,0x31,0x0f,0x16,0x26,0x36,0x0f,0x12,0x22,0x32,0x0f,0x2a,0x30,0x1a,0x0f,0x11,0x21,0x31,0x0f,0x16,0x26,0x36,0x0f,0x12,0x22,0x32]);
for(const [pos,name,relative] of fixups){const dest=labels.get(name);if(dest===undefined)throw Error(name);if(relative){const delta=dest-(0x8000+pos+1);if(delta < -128 || delta>127)throw Error('branch range');code[pos]=delta&255;}else{code[pos]=dest&255;code[pos+1]=dest>>8;}}
const prg=Buffer.alloc(16384,0xea);Buffer.from(code).copy(prg);
for(const [offset,name] of [[0x3ffa,'nmi'],[0x3ffc,'reset'],[0x3ffe,'nmi']])prg.writeUInt16LE(labels.get(name),offset);
const chr=Buffer.alloc(8192);for(let row=0;row<8;row++)chr[16+row]=0xff;
const header=Buffer.from([0x4e,0x45,0x53,0x1a,1,1,2,0,0,0,0,0,0,0,0,0]);
const out=process.argv[2]||'assets/demo/retrotv-pad-test.nes';fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,Buffer.concat([header,prg,chr]));
console.log(`Original CC0 NES pad/audio test: ${out} (${16+prg.length+chr.length} bytes)`);
